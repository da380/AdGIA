// ============================================================================
// manufactured_fluid_benchmark.cpp
//
// The method of manufactured solutions for the static self-gravitating
// problem with a closed fluid core: LinearQuasiStaticMixedSelfGravitatingProblem
// with the core as a FluidRegion and the level border of the Dahlen
// closure (SetLevelBorder), on a two-layer ball (fluid core, solid
// shell, buffer; meshes/layered_earth.py --layers 2 --dim 3). The exact
// fields and every load -- the displacement row's, the potential row's
// and the border rows' -- are those of fields_fluid.hpp, generated by
// manufacture_fluid.py; fluid_case.hpp applies them, solves and measures
// (its header comment states the placement of each source and the error
// measures).
//
// Options: the level count (-levels), the border's reading of the
// background (-exact-levels: the analytic Phi0; -projected-levels: its
// projection), the assembly of the gravity term (the class default, the
// Hessian of the discrete Phi0; -exact-hessian; -interpolant), and the
// sensitivity switches that drop the border data or the CMB traction.
//
// Sample run:
//    mpiexec -np 4 ./manufactured_fluid_benchmark \
//        -m ../../data/earth_fluidcore_3d.msh -o 2 -levels 16 -out o2.json
// ============================================================================

#include <chrono>
#include <format>
#include <fstream>
#include <iostream>
#include <string>

#include "fluid_case.hpp"
#include "mfem.hpp"

using namespace mfem;
namespace mf = manufactured_fluid;

int main(int argc, char* argv[]) try {
  Mpi::Init(argc, argv);
  Hypre::Init();
  const bool root = Mpi::Root();
  using Clock = std::chrono::steady_clock;

  const char* mesh_file = "../../data/earth_fluidcore_3d.msh";
  const char* out_file = "manufactured_fluid.json";
  int order = 2, order_phi = 0;
  mf::Options opt;
  bool exact_hessian = false, interpolant = false, no_border = false,
       no_cmb_traction = false, print_border = false;

  OptionsParser args(argc, argv);
  args.AddOption(&mesh_file, "-m", "--mesh",
                 "A two-layer ball: attributes 1 fluid core, 2 solid "
                 "shell, 3 buffer; boundary attributes 1 CMB, 2 surface.");
  args.AddOption(&out_file, "-out", "--output", "Results file (JSON).");
  args.AddOption(&order, "-o", "--order", "Finite element order.");
  args.AddOption(&order_phi, "-ophi", "--order-phi",
                 "Order of the potential space (0: the displacement's).");
  args.AddOption(&opt.levels, "-levels", "--levels",
                 "Nodes of the level border's grid.");
  args.AddOption(&opt.exact_levels, "-exact-levels", "--exact-levels",
                 "-projected-levels", "--projected-levels",
                 "The border reads the analytic Phi0 and its gradient "
                 "(SetLevelBorder(levels, true, grad_phi0)) or the "
                 "projected Phi0.");
  args.AddOption(&opt.dtn_degree, "-deg", "--dtn-degree", "DtN degree.");
  args.AddOption(&opt.rel_tol, "-rt", "--rel-tol", "Solver tolerance.");
  args.AddOption(&exact_hessian, "-exact-hessian", "--exact-hessian",
                 "-discrete-hessian", "--discrete-hessian",
                 "Assemble the gravity term by the product rule with the "
                 "EXACT Hessian of Phi0 instead of the class's default, "
                 "the Hessian of the discrete Phi0.");
  args.AddOption(&interpolant, "-interpolant", "--interpolant", "-hessian",
                 "--hessian",
                 "The nodal interpolant of u.grad Phi0 instead of the "
                 "product rule.");
  args.AddOption(&no_border, "-no-border-sources", "--no-border-sources",
                 "-border-sources", "--border-sources",
                 "Drop the border rows' data (a sensitivity check: the "
                 "solution then misses the exact one by O(1)).");
  args.AddOption(&no_cmb_traction, "-no-cmb-traction", "--no-cmb-traction",
                 "-cmb-traction", "--cmb-traction",
                 "Drop the CMB traction (a sensitivity check).");
  args.AddOption(&opt.strong_border, "-strong-border", "--strong-border",
                 "-weak-border", "--weak-border",
                 "The U row's data from the source density r_U and the "
                 "wall's point source instead of the weak residual "
                 "(identical up to quadrature).");
  args.AddOption(&opt.sphere_normal, "-sphere-normal", "--sphere-normal",
                 "-facet-normal", "--facet-normal",
                 "Evaluate the surface data with the exact sphere's normal "
                 "instead of the facet's own.");
  args.AddOption(&print_border, "-print-border", "--print-border",
                 "-no-print-border", "--no-print-border",
                 "Print the border solution against the exact one, node "
                 "by node.");
  args.Parse();
  if (!args.Good()) {
    if (root) args.PrintUsage(std::cout);
    return 1;
  }
  if (root) args.PrintOptions(std::cout);
  MFEM_VERIFY(!(exact_hessian && interpolant), "one gravity route");
  opt.gravity = exact_hessian ? mf::Gravity::ExactHessian
                : interpolant ? mf::Gravity::Interpolant
                              : mf::Gravity::Default;
  opt.border_sources = !no_border;
  opt.cmb_traction = !no_cmb_traction;

  const auto t_start = Clock::now();
  Mesh smesh(mesh_file, 1, 1);
  MFEM_VERIFY(smesh.Dimension() == 3, "three dimensions");
  ParMesh parent(MPI_COMM_WORLD, smesh);
  smesh.Clear();
  Array<int> shell_attr({mf::kShellAttr});
  ParSubMesh solid(ParSubMesh::CreateFromDomain(parent, shell_attr));
  if (order_phi <= 0) order_phi = order;
  H1_FECollection fec(order, 3), fec_phi(order_phi, 3);
  ParFiniteElementSpace fes_u(&solid, &fec, 3), fes_phi(&parent, &fec_phi);

  const mf::Results r = mf::Solve(fes_u, fes_phi, opt);

  double h_min, h_max, k_min, k_max;
  parent.GetCharacteristics(h_min, h_max, k_min, k_max);
  const long ne = parent.GetGlobalNE();
  const double total_s =
      std::chrono::duration<double>(Clock::now() - t_start).count();
  const char* gravity = exact_hessian ? "exact-hessian"
                        : interpolant ? "interpolant"
                                      : "discrete-hessian";

  if (root) {
    std::cout << std::format(
        "order {} (phi {}) levels {} ({}) elements {} dofs u {} phi {} "
        "h [{:.4g}, {:.4g}]\n"
        "  |u_h - u*|/|u*|             {:.3e} (shell)\n"
        "  |sigma_h - sigma*|/|sigma*| {:.3e} (shell)\n"
        "  |phi_h - phi*|/|phi*|       {:.3e} (ball), {:.3e} (core)\n"
        "  border U  max {:.3e} rms {:.3e} volume-weighted {:.3e}\n"
        "  border s  max {:.3e} rms {:.3e} volume-weighted {:.3e}\n"
        "  border nu max {:.3e} rms {:.3e} volume-weighted {:.3e}\n"
        "  wall multiplier {:.10g} (exact {:.10g}): {:.3e}\n"
        "  grid [{:.10g}, {:.10g}] against [c_min, c_w] = [{:.10g}, {:.10g}]\n"
        "  rigid part removed {:.3e}\n"
        "  facet normals against the solid's outward one: SubMesh CMB {}/{}, "
        "surface {}/{}; parent CMB pointing away from the centre {}/{}\n"
        "  iterations {} solve {:.2f} s total {:.2f} s\n",
        order, order_phi, opt.levels,
        opt.exact_levels ? "exact levels" : "projected levels", ne, r.dofs_u,
        r.dofs_phi, h_min, h_max, r.u, r.stress, r.phi, r.phi_core, r.U_max,
        r.U_rms, r.U_vol, r.s_max, r.s_rms, r.s_vol, r.nu_max, r.nu_rms,
        r.nu_vol, r.lambda_h,
        mf::kLambda, r.lambda, r.c_lo, r.c_hi, mf::kCMin,
        mf::kCWall, r.rigid, r.flipped_cmb, r.facets_cmb,
        r.flipped_surface, r.facets_surface, r.parent_cmb_up, r.facets_cmb,
        r.iterations, r.solve_seconds, total_s);
    std::cout << std::format(
        "  border rows' residual at the exact solution: U {:.3e} s {:.3e} "
        "nu {:.3e} wall {:.3e}\n"
        "  border element volumes against the analytic shells: max {:.3e} "
        "rms {:.3e}\n",
        r.res_U, r.res_s, r.res_nu, r.res_lambda, r.vol_max, r.vol_rms);
    if (print_border) {
      std::cout << "  node  c  U_h  U*  s_h  s*  nu_h  nu*\n";
      for (int k = 0; k < r.c.Size(); k++) {
        std::cout << std::format(
            "  {:3d} {:.8f} {: .6e} {: .6e} {: .6e} {: .6e} {: .6e} {: .6e}\n",
            k, r.c[k], r.U[k], mf::d3::border_U(r.c[k]), r.s[k],
            mf::d3::border_s(r.c[k]), r.nu[k], mf::d3::border_nu(r.c[k]));
      }
    }
    std::ofstream out(out_file);
    out << std::format(
        "{{\n  \"mesh\": \"{}\",\n  \"order\": {},\n  \"order_phi\": {},\n"
        "  \"levels\": {},\n  \"exact_levels\": {},\n  \"gravity\": \"{}\",\n"
        "  \"border_sources\": {},\n  \"cmb_traction\": {},\n"
        "  \"strong_border\": {},\n  \"sphere_normal\": {},\n"
        "  \"dtn_degree\": {},\n  \"rel_tol\": {:.3g},\n"
        "  \"elements\": {},\n  \"dofs_u\": {},\n  \"dofs_phi\": {},\n"
        "  \"h_min\": {:.17g},\n  \"h_max\": {:.17g},\n"
        "  \"u_l2\": {:.17g},\n  \"stress_l2\": {:.17g},\n"
        "  \"phi_l2\": {:.17g},\n  \"phi_core_l2\": {:.17g},\n"
        "  \"U_max\": {:.17g},\n  \"U_rms\": {:.17g},\n"
        "  \"s_max\": {:.17g},\n  \"s_rms\": {:.17g},\n"
        "  \"nu_max\": {:.17g},\n  \"nu_rms\": {:.17g},\n"
        "  \"U_vol\": {:.17g},\n  \"s_vol\": {:.17g},\n"
        "  \"nu_vol\": {:.17g},\n"
        "  \"res_U\": {:.17g},\n  \"res_s\": {:.17g},\n"
        "  \"res_nu\": {:.17g},\n  \"res_lambda\": {:.17g},\n"
        "  \"vol_max\": {:.17g},\n  \"vol_rms\": {:.17g},\n"
        "  \"lambda\": {:.17g},\n  \"lambda_h\": {:.17g},\n"
        "  \"c_lo\": {:.17g},\n  \"c_hi\": {:.17g},\n"
        "  \"rigid\": {:.17g},\n"
        "  \"iterations\": {},\n  \"solve_seconds\": {:.6g},\n"
        "  \"total_seconds\": {:.6g},\n  \"ranks\": {}\n}}\n",
        mesh_file, order, order_phi, opt.levels, opt.exact_levels, gravity,
        opt.border_sources, opt.cmb_traction, opt.strong_border,
        opt.sphere_normal, opt.dtn_degree, opt.rel_tol, ne, r.dofs_u,
        r.dofs_phi, h_min, h_max, r.u, r.stress, r.phi, r.phi_core, r.U_max,
        r.U_rms, r.s_max, r.s_rms, r.nu_max, r.nu_rms, r.U_vol, r.s_vol,
        r.nu_vol, r.res_U, r.res_s, r.res_nu, r.res_lambda, r.vol_max,
        r.vol_rms, r.lambda, r.lambda_h,
        r.c_lo, r.c_hi, r.rigid, r.iterations, r.solve_seconds, total_s,
        Mpi::WorldSize());
  }
  return 0;
} catch (const std::exception& e) {
  std::cerr << "manufactured_fluid_benchmark: " << e.what() << "\n";
  return 1;
}
