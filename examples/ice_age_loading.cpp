// ============================================================================
// ice_age_loading.cpp
//
// Viscoelastic sea-level response to a real deglaciation: the ICE-7G
// ice history (data downloaded and cached by pyslfp; nothing is bundled
// here) loaded onto a Maxwell planet with the monolithic water-load
// feedback (SetWaterLoad, frozen shorelines at the linearisation
// instant = the oldest date), stepped through the history, chaining the
// surface exchange format end to end.
//
// The chain has steps 0-3; steps 1 and 3 are this program, step 0 is
// optional. The build's data/earth_coastlines.msh — refined along the real
// coastlines and the shallow shelves (one sizing field, no coastline
// isolation) — suits every run below through
// -m ../data/earth_coastlines.msh; an optional step 0 rebuilds it from
// a sharper or re-dated topography (meshes/README.md, "The coastline
// mesh"):
//
//   0.  <build>/earth_data/topography_grid --lmax 96
//       poetry -P meshes run python meshes/earth_coastlines.py \
//           --topography topography.npz --coast-size 0.03 --out <build>/data
//
//   1.  ./ice_age_loading                 # no -ice: writes the surface
//       node CSV (ice_age_nodes.csv) and prints step 2's commands.
//   2.  <build>/earth_data/ice_ng_to_surface ice_age_nodes.csv \
//           --dates 21,19,17,15,13,11,9,7,5,3,1,0 --length-scale 6.371e6
//       <build>/earth_data/ice_ng_to_surface ice_age_nodes.csv \
//           --field sea_level --dates 21 --length-scale 6.371e6 \
//           -o ice_age_nodes_state.csv
//       (pyslfp samples ICE-7G at the nodes; lengths in planet radii,
//       model time in ka from the oldest date. The CSVs are exact
//       nodal data: the node set depends on the mesh AND the order,
//       so changing -m or -o means re-running steps 1 and 2.)
//   3.  ./ice_age_loading -ice ice_age_nodes_ice.csv \
//                         -state ice_age_nodes_state.csv
//
// Step 3 reads both stacks (IceHistory), freezes the ocean function at
// the first field's flotation, steps the Maxwell body with the
// time-interpolated grounded-ice load sigma_d(t) = rho_i (1 - C0) dI(t)
// inside the water-load solve, prints a per-step table (eustatic
// equivalent, ocean-mean sea level, Phi_g, displacement norm), writes
// the history CSV for plot_csv.py and the final fingerprint CSV for the
// map chain, and opens GLVis windows.
//
// The body is the toy homogeneous planet of the sea-level examples
// (non-dimensional; the real geography rides a model rheology), so the
// output is qualitative: the realistic-Earth runs belong to the
// benchmarks and the server. Time is measured in the stacks' model-time
// unit (ka as exported above); -tau sets the Maxwell time in that unit.
//
// One source serves the serial and the parallel build (np N gives the
// same numbers).
//
// Mesh requirements. Default ../data/ball_buffer_coarse_3d.msh, generated by
// meshes/homogeneous_body.py --preset ball-buffer-coarse: a 3-D unit ball (attribute 1, the body)
// inside a buffer to r = 2 (attribute 2); boundary attribute 1 is the
// ball's surface, 2 the outer sphere. The ice chain needs this 3-D ball
// (or earth_coastlines.msh, same layout). The unit radius is the planet
// radius: the stack lengths are exported with --length-scale 6.371e6, so
// one model length is 6.371e6 m. With -fluid-core the mesh must instead be
// ../data/earth_innercore_3d.msh (meshes/layered_earth.py):
// domain attributes 1 solid inner core, 2 fluid outer core, 3 mantle,
// 4 buffer (to r = 1.2); boundary attributes 1 ICB, 2 CMB, 3 surface,
// 4 outer; the ICB and CMB radii 0.1931 and 0.5467 are hard-coded for the
// shear-modulus layering and the kernel sampling. Surface conventions:
// on the body SubMesh the surface is the highest boundary attribute; on
// the parent mesh it is boundary attribute 1 (ball) or 3 (three-layer),
// used by the potential-side observation dual. Constants (G, rho, kappa,
// mu) are nondimensional (the toy body of the sea-level examples).
//
// Options (defaults in brackets):
//   -m       body-in-buffer mesh [../data/ball_buffer_coarse_3d.msh]; the
//            ice chain needs the 3-D ball.
//   -o       finite element order [1].
//   -r       uniform refinements [0].
//   -ice     the ice-thickness time stack (step 2) [""].
//   -state   the initial sea-level stack; its FIRST column is the
//            linearisation state [""].
//   -rhow / -rhoi   water and ice density, body units [0.19, 0.17].
//   -shore   flotation smoothing width (rho_w x length units) [1e-4].
//   -tau     Maxwell time of the mantle, stack time units [0.5].
//   -n       time steps over the stack's span [40].
//   -rt      relative solver tolerance [1e-11: the stepped bordered
//            solves accumulate and amplify solver noise, and the early
//            history's small fields drown at looser settings].
//   -nodes-csv   step-1 output [ice_age_nodes.csv].
//   -csv     per-step history table [ice_age_loading.csv].
//   -fluid-core / -no-fluid-core   three-layer planet with an inviscid
//            outer core [off]; needs the three-layer mesh (see Mesh
//            requirements). The core is handled by the gauge-penalty
//            fluid treatment (uniform density, zero fluid shear); the
//            viscosity-kernel shells then start at r = 0.60 and the
//            slice at the CMB.
//   -lateral-visc   relative amplitude a of a smooth degree-2 lateral
//            viscosity variation of the base model [0]:
//            tau(x) = tau_m (1 + a [(x^2 - y^2) + 0.7 x z] / r^2);
//            keep |a| < 0.5.
//   -kernel / -no-kernel   adjoint sensitivity kernels [off]: after the
//            forward run, ONE adjoint sweep (the common adjoint
//            structure, adjoint.hpp) gives the kernels of a present-day
//            windowed sea-level observation at (-obs-lat, -obs-lon)
//            [Boston] with respect to (i) the mantle VISCOSITY — the
//            3-D volume field, shown in GLVis — and (ii) the ICE
//            HISTORY in the quelled rate parameterisation: the
//            optimisation-ready D_Idot(x, t) surface kernels of Yu et
//            al. (2025, eq. 84), exported at -nk epochs as
//            ice_kernel_t*.csv for the pyslfp map chain
//            (<build>/earth_data/plot_fingerprint_kernel, ice-masked
//            panels, two epochs side by side). With the frozen-C0
//            ocean of this chain the I0 kernel vanishes identically
//            (eq. 84's (C - C0) factor) and is not exported. USE
//            -o 2: at order 1 the internal-variable space has order
//            zero and the localised viscoelastic kernel structure is
//            unreliable; the run warns. Outputs: ice_kernel_t<t>.csv
//            (D_Idot at the -nk epochs, WriteSurfaceField format),
//            visc_kernel_r<r>.csv (the viscosity kernel on the -nd depth
//            shells, x,y,z,value), visc_kernel_slice.csv (the
//            great-circle slice through the site, alpha_deg,r,value) and
//            visc_kernel.mesh / visc_kernel.gf (GLVis cutting planes),
//            all in the working directory.
//   -obs-lat -obs-lon   observation site, degrees [42.36, -71.06].
//   -obs-width   angular width (rad) of the observation window [0.1].
//   -nk      number of D_Idot epochs exported [4] (0: none).
//   -nd      number of viscosity-kernel depth shells exported [3] (0:
//            none; the slice is written regardless). Serial and
//            parallel runs alike: the root rank samples the gathered
//            kernel.
//   -taylor  Taylor-test points per side of s = 0 [0: off]: exact
//            J(m0 + s dm) against the first-order affine prediction
//            J0 + s dJ[dm], for a viscosity blob under Hudson Bay and a
//            Greenland ice-rate cap; writes taylor_test.csv and
//            taylor_remainder.csv (needs the adjoint run, so it also
//            runs the sweep without -kernel).
//   -smax    largest |s| of the Taylor test [1].
//   -vis / -no-vis   GLVis windows [on].
//
// Sample runs (with mpiexec -np N in front in a parallel build):
//    ./ice_age_loading
//    ./ice_age_loading -ice ice_age_nodes_ice.csv \
//                      -state ice_age_nodes_state.csv
//    ./ice_age_loading -ice ice_age_nodes_ice.csv \
//                      -state ice_age_nodes_state.csv -tau 0.3 -n 80
//    ./ice_age_loading -ice ice_age_nodes_ice.csv \
//                      -state ice_age_nodes_state.csv -o 2 -kernel -nd 3
// ============================================================================

