// ============================================================================
// generalised_rotation.cpp
//
// The generalised rotational theory on a triaxial body (Maitra &
// Al-Attar 2024).
//
// The traditional rotational feedback (Yu, Al-Attar, Syvret & Lloyd
// 2025, §2.3–2.4) determines the rotation perturbation omega from the
// angular-momentum row
//
//     D omega + int rho u . grad psi_k dV + int sigma psi_k dS = 0,
//
// with D built from OBSERVED principal moments. But u is defined only
// modulo rigid motions, and under a re-gauge u -> u + b x x the row
// shifts by the closed form
//
//     delta omega = D^{-1} [ad_b, I] Omega,
//
// with I the MODEL's inertia tensor: zero iff I is isotropic (the
// paper's eq. 20). On a spherical model the gauge freedom is harmless;
// on a triaxial one it is an O(1) ambiguity of omega with no small
// parameter. The Maitra & Al-Attar (2024) theory removes it: the
// Tisserand condition int rho x cross u dV = 0 pins the representative
// before omega is ever read, and the secular limit of their linearised
// Euler equation is exactly the traditional row with D built from the
// model's own moments (Maitra & Al-Attar 2024).
//
// The example builds a ball with a triaxial density, solves the loaded
// rotation problem through both doors of the referential class, and
// shows:
//   1. the traditional omega shifts under rigid re-gauges of u — the
//      sweep over the gauge amplitude is written as a CSV curve, with
//      the closed-form prediction on top of the measured shift, and a
//      spherical control where both collapse;
//   2. the Tisserand-pinned row is representative-independent (machine
//      zeros in the same sweep);
//   3. the generalised door's omega (SetRotation(Omega): model inertia
//      + Tisserand gauge) equals the traditional omega corrected by the
//      closed-form gauge term of ITS representative — one formula
//      connects the two theories.
//
// The reference state is the uniform-ball hydrostatic pressure: with
// the mild triaxiality this background is inconsistent at the percent
// level, which is fine for a demonstration of the GAUGE structure (the
// rows and the gauge are exact for whatever operator is assembled). On
// a near-spherical model the model-inertia door refuses (no finite
// wander response of its own) and points to the input-moments option
// SetRotation(Omega, moments) + SetTisserandGauge(true). The
// traditional door below uses SetRotation(Omega, moments) without the
// gauge; the spherical control is the spherical density's row alone.
//
// 3-D only (the rotation border). One source serves the serial and the
// parallel build; the only genuine differences are the partitioning and
// the global reductions of the quadrature instruments.
//
// Mesh requirements. Default ../data/ball_buffer_coarse_3d.msh, generated by
// meshes/ball_with_buffer.py: a 3-D unit ball (attribute 1, the body)
// inside a buffer to r = 2 (attribute 2, the vacuum-extension domain).
// The loaded surface is the body boundary with the highest boundary
// attribute. The unit body radius is assumed by Pressure() and by the
// radial vacuum extension. All constants (G = 0.05, rho = 1, kappa = 1,
// mu = 0.5, Omega) are nondimensional.
//
// Options (defaults in brackets):
//   -m       mesh file [../data/ball_buffer_coarse_3d.msh] (body-in-buffer ball).
//   -o       finite element order [2].
//   -Omega   equilibrium rotation rate about e3 [0.1].
//   -ez      zonal density perturbation amplitude [0.1]:
//            rho = 1 + ez (3 z^2 - r^2) + et (x^2 - y^2).
//   -et      equatorial (triaxial) amplitude [0.05].
//   -csv     CSV file of the gauge sweep [generalised_rotation.csv];
//            empty disables. Plot with: python3 plot_csv.py <file>.
//   -vis / -no-vis   GLVis windows on or off [on].
//
// Sample runs (with mpiexec -np N in front in a parallel build):
//    ./generalised_rotation
//    ./generalised_rotation -ez 0.2 -et 0.1
//    ./generalised_rotation -o 1 -no-vis
// ============================================================================

